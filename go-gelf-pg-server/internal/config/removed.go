// removedEnvWarnings names every removed variable that is set, in one line.
func removedEnvWarnings(lookup func(string) (string, bool)) []string {
	var set []string
	for _, k := range removedEnv {
		if _, ok := lookup(k); ok {
			set = append(set, k)
		}
	}
	if len(set) == 0 {
		return nil
	}
	sort.Strings(set)
	return []string{fmt.Sprintf("%s: set in the environment, but go-gelf-pg-server has no such "+
		"parameter (no TLS or HTTPS, no other sink or ring, no filter, rate limiter or beacon; SPEC §1.2). "+
		"Ignored", strings.Join(set, ", "))}
}

